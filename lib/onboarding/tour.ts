export function tourSteps(canAccess: (module: string) => boolean): TourStep[] {
 return [...basics.map(([title,body],index)=>({id:'basic-'+index,title,body})),
 ...navItems.filter(item=>canAccess(item.moduleKey)).map(item=>({id:'section-'+item.id,title:item.label,
 body:descriptions[item.id] || `هذا قسم ${item.label}. افتحه للتعرّف على البيانات والإجراءات المتاحة لحسابك؛ راجع تفاصيل السجل قبل اتخاذ إجراء.`,href:item.href}))];
}
